function detect() {
  try {
    const saved = localStorage.getItem("lang");
    if (saved === "fr" || saved === "en") return saved;
  } catch { /* stockage indisponible */ }
  return (navigator.language || "en").toLowerCase().startsWith("fr") ? "fr" : "en";
}

let lang = detect();

export const getLang = () => lang;

export function t(key, params = {}) {
  const v = DICT[lang][key] ?? DICT.fr[key] ?? key;
  return typeof v === "function" ? v(params) : v;
}

/** Applique les textes statiques marqués data-i18n (texte), -html, -ph, -title, -aria. */
export function applyStatic() {
  document.documentElement.lang = lang;
  document.querySelectorAll("[data-i18n]").forEach((e) => (e.textContent = t(e.dataset.i18n)));
  document.querySelectorAll("[data-i18n-html]").forEach((e) => (e.innerHTML = t(e.dataset.i18nHtml))); // textes du dictionnaire uniquement
  document.querySelectorAll("[data-i18n-ph]").forEach((e) => (e.placeholder = t(e.dataset.i18nPh)));
  document.querySelectorAll("[data-i18n-title]").forEach((e) => (e.title = t(e.dataset.i18nTitle)));
  document.querySelectorAll("[data-i18n-aria]").forEach((e) => e.setAttribute("aria-label", t(e.dataset.i18nAria)));
}

export function setLang(next) {
  if (next !== "fr" && next !== "en") return;
  lang = next;
  try { localStorage.setItem("lang", next); } catch { /* ignoré */ }
  applyStatic();
}
